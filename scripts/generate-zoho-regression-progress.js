// Regenerates tests/zoho-regression/README.md -- a per-module progress dashboard for the Zoho
// historical bug regression effort. Re-run this after updating matchedTestId entries in
// config/zohoBugMap.js so the counts stay accurate.
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const { TEACH_MODE_BUGS, EXCLUDED_PLAN_MODE_BUGS, OPEN_STATUSES } = require(path.join(
  ROOT,
  'config',
  'zohoBugMap.js'
));

const MODULE_SLUGS = {
  'AI Assist': 'ai-assist',
  'AI Homework': 'ai-homework',
  'AI Notices': 'ai-notices',
  'Add Resource': 'add-resource',
  Attendance: 'attendance',
  'Authentication / Sign-In': 'authentication',
  Compass: 'compass',
  'Compass (AfL Reports)': 'compass-afl-reports',
  'Core UI': 'core-ui',
  'Drop It': 'drop-it',
  'Grade / Subject / Division': 'grade-subject-division',
  'Magnet (entry point -> Attendance/Homework/Notices/Learning Shorts)': 'magnet',
  'Ops / Infra (non-UI)': 'ops-infra',
  'Players (Checkpoint)': 'players-checkpoint',
  'Players (Code Editor)': 'players-code-editor',
  'Players (Ebook)': 'players-ebook',
  'Players (Quiz)': 'players-quiz',
  'Players (Worksheet)': 'players-worksheet',
  Playlist: 'playlist',
  'Student Test / Reports': 'student-test-reports',
  'TCE Search Library': 'tce-search-library',
  Toolbar: 'toolbar',
  'Unclassified / Needs Review': 'unclassified',
  'User Profile': 'user-profile',
  Whiteboard: 'whiteboard',
};

const byModule = {};
for (const bug of TEACH_MODE_BUGS) {
  byModule[bug.module] ??= { total: 0, open: 0, matched: 0 };
  byModule[bug.module].total += 1;
  if (OPEN_STATUSES.includes(bug.status)) byModule[bug.module].open += 1;
  if (bug.matchedTestId) byModule[bug.module].matched += 1;
}

const rows = Object.keys(MODULE_SLUGS)
  .filter((m) => byModule[m])
  .map((m) => {
    const { total, open, matched } = byModule[m];
    const slug = MODULE_SLUGS[m];
    return `| ${m} | [${slug}.spec.js](./${slug}.spec.js) | ${total} | ${open} | ${matched} | ${total - matched} |`;
  });

const totals = Object.values(byModule).reduce(
  (acc, v) => ({ total: acc.total + v.total, open: acc.open + v.open, matched: acc.matched + v.matched }),
  { total: 0, open: 0, matched: 0 }
);

const md = `# Zoho Historical Bug Regression -- Progress

Auto-generated by \`node scripts/generate-zoho-regression-progress.js\` from \`config/zohoBugMap.js\`.
Do not hand-edit; re-run the script after updating \`matchedTestId\` entries.

**Rule:** a bug's Zoho status (open/closed/reopened) is never a reason to skip it. The only valid
reason a bug stays unmatched is that it's genuinely not yet automated. The only valid reason to
exclude one permanently is that an existing test case (in \`tests/\` or a
\`CEP_TestCases/*_Module_Test_Cases_Final.xlsx\`) already proves that exact defect -- point
\`matchedTestId\` at that and it drops out of "Remaining" here.

${EXCLUDED_PLAN_MODE_BUGS.length} Plan Mode bugs are out of scope entirely (this suite only drives
Teach Mode) and are not counted below.

| Module | Spec file | Total bugs | Open (Zoho) | Automated | Remaining |
|---|---|---:|---:|---:|---:|
${rows.join('\n')}
| **Total** | | **${totals.total}** | **${totals.open}** | **${totals.matched}** | **${totals.total - totals.matched}** |
`;

fs.writeFileSync(path.join(ROOT, 'tests', 'zoho-regression', 'README.md'), md);
console.log('Wrote tests/zoho-regression/README.md');
