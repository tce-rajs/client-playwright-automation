// One-off generator: reads CEP_TestCases/Zoho_Bugs_TeachMode.xlsx and writes
// config/zohoBugMap.js. Re-run this if the source workbook is ever updated.
const xlsx = require('xlsx');
const fs = require('fs');
const path = require('path');

const wb = xlsx.readFile(path.join(__dirname, '..', 'CEP_TestCases', 'Zoho_Bugs_TeachMode.xlsx'));
const teach = xlsx.utils.sheet_to_json(wb.Sheets['Teach Mode Bugs'], { defval: '' });
const plan = xlsx.utils.sheet_to_json(wb.Sheets['Excluded - Plan Mode'], { defval: '' });

function jsLiteral(value) {
  return JSON.stringify(String(value).replace(/\r?\n/g, ' ').trim());
}

function toEntry(r) {
  return (
    '  { id: ' +
    jsLiteral(r['Item Id']) +
    ', module: ' +
    jsLiteral(r.Module) +
    ', title: ' +
    jsLiteral(r['Item Name']) +
    ', priority: ' +
    jsLiteral(r.Priority) +
    ', status: ' +
    jsLiteral(r.Status) +
    ", matchedTestId: null, notes: '' },"
  );
}

const lines = [];
lines.push('// Zoho historical bug -> automated test mapping.');
lines.push('// Source: CEP_TestCases/Zoho_Bugs_TeachMode.xlsx (620 Teach Mode bugs, 73 excluded Plan');
lines.push('// Mode bugs, re-scoped/re-classified from the original 693-bug Zoho Sprints export -- see');
lines.push('// CEP_TestCases/SENIOR_AUTOMATION_STRATEGY_REPORT.md for the analysis this refines).');
lines.push('// Generated by scripts/generate-zoho-bug-map.js -- re-run that script if the source');
lines.push('// workbook changes, rather than hand-editing the generated arrays below.');
lines.push('//');
lines.push('// Purpose: track, per historical bug, whether an existing or new Playwright test actually');
lines.push('// verifies its CURRENT live status. Fill in matchedTestId (e.g. a real test title/ID in');
lines.push('// tests/zoho-regression/ or an existing module spec file) once a real Playwright test proves');
lines.push('// -- pass or fail -- whether this exact defect reproduces today. Leave matchedTestId null');
lines.push("// until that's true; don't fill it in just because the bug LOOKS related to an existing test.");
lines.push('');
lines.push('const TEACH_MODE_BUGS = [');
teach.forEach((r) => lines.push(toEntry(r)));
lines.push('];');
lines.push('');
lines.push("// Excluded: confirmed Planning-mode-only repro (out of this suite's current Teaching-mode");
lines.push('// scope). Kept here, not deleted, so a future scope change can reuse this list.');
lines.push('const EXCLUDED_PLAN_MODE_BUGS = [');
plan.forEach((r) => lines.push(toEntry(r)));
lines.push('];');
lines.push('');
lines.push('function getByModule(moduleName) {');
lines.push('  return TEACH_MODE_BUGS.filter((b) => b.module === moduleName);');
lines.push('}');
lines.push('');
lines.push('function getUnmatched() {');
lines.push('  return TEACH_MODE_BUGS.filter((b) => !b.matchedTestId);');
lines.push('}');
lines.push('');
lines.push("const OPEN_STATUSES = ['To do', 'Reopened', 'Ready for Testing', 'On Hold'];");
lines.push('');
lines.push('function getOpen() {');
lines.push('  return TEACH_MODE_BUGS.filter((b) => OPEN_STATUSES.includes(b.status));');
lines.push('}');
lines.push('');
lines.push(
  'module.exports = { TEACH_MODE_BUGS, EXCLUDED_PLAN_MODE_BUGS, OPEN_STATUSES, getByModule, getUnmatched, getOpen };'
);

const outPath = path.join(__dirname, '..', 'config', 'zohoBugMap.js');
fs.writeFileSync(outPath, lines.join('\n') + '\n', 'utf8');
console.log('Wrote', outPath, '-', teach.length, 'teach-mode +', plan.length, 'plan-mode entries');
